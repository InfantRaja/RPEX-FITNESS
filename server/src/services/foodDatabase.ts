export function searchFoods(query: string = '', filters?: {
  category?: string;
  dietPreference?: string;
  isBudgetFriendly?: boolean;
  allergies?: string[];
}): DatabaseFoodItem[] {
  let results = [...VERIFIED_FOOD_DATABASE];

  if (query && query.trim()) {
    const q = query.toLowerCase().trim();
    results = results.filter(f => f.name.toLowerCase().includes(q) || f.category.toLowerCase().includes(q));
  }

  if (filters?.category && filters.category !== 'all') {
    results = results.filter(f => f.category === filters.category);
  }

  if (filters?.dietPreference && filters.dietPreference !== 'none') {
    const pref = filters.dietPreference;
    results = results.filter(f => f.dietType.includes(pref as any));
  }

  if (filters?.isBudgetFriendly) {
    results = results.filter(f => f.isBudgetFriendly);
  }

  if (filters?.allergies && filters.allergies.length > 0) {
    const userAllergens = filters.allergies.map(a => a.toLowerCase().trim());
    results = results.filter(f => {
      if (!f.allergens) return true;
      return !f.allergens.some(a => userAllergens.includes(a.toLowerCase()));
    });
  }

  return results;
}
